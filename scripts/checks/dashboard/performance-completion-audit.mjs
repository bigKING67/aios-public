#!/usr/bin/env node

import {
  existsSync,
  readFileSync,
  statSync,
} from 'node:fs';
import path from 'node:path';

const ENDPOINTS = Object.freeze(['traffic', 'traffic_goods', 'goods']);
const AUDIT_TARGETS = Object.freeze(new Set(['vps-runtime', 'local-artifacts']));

function printUsage() {
  console.log(`Usage: node scripts/checks/dashboard-performance-completion-audit.mjs [options]

Audits the real evidence needed before calling the dashboard quality/performance
work complete. This is intentionally stricter than CI: it checks local or VPS
artifacts generated by live observations.

Options:
  --target <vps-runtime|local-artifacts>
                                      Default: DASHBOARD_PERFORMANCE_AUDIT_TARGET or vps-runtime.
                                      vps-runtime requires systemd evidence; local-artifacts skips only
                                      the VPS systemd unit check while preserving artifact freshness/status checks.
  --latency-artifact-dir <path>       Default: DASHBOARD_API_LATENCY_ARTIFACT_DIR or .artifacts/dashboard-api-latency
  --frontend-smoke-history <path>     Default: FRONTEND_SMOKE_HISTORY_JSONL or .artifacts/frontend-smoke-performance/history.jsonl
  --frontend-smoke-report <path>      Default: FRONTEND_SMOKE_REPORT_MD or .artifacts/frontend-smoke-performance/latest.md
  --systemd-unit-dir <path>           Default: DASHBOARD_LATENCY_SYSTEMD_UNIT_DIR or /etc/systemd/system
  --systemd-service-name <name>       Default: aios-dashboard-latency-observation
  --max-age-hours <hours>             Default: DASHBOARD_PERF_AUDIT_MAX_AGE_HOURS or 168
  --require-cache-hit <0|1>           Default: DASHBOARD_PERF_AUDIT_REQUIRE_CACHE_HIT or 1
  --skip-frontend-smoke               Do not require authenticated frontend smoke artifacts.
  --skip-systemd                      Do not require installed systemd service/timer files.
  --json                              Print machine-readable JSON.
  --help                              Show this help.
`);
}

function readValueArg(args, index, name) {
  const value = args[index + 1];
  if (!value || value.startsWith('--')) {
    throw new Error(`${name} requires a value`);
  }
  return value;
}

function parsePositiveNumber(name, value) {
  const parsed = Number(value);
  if (!Number.isFinite(parsed) || parsed <= 0) {
    throw new Error(`${name} must be a positive number`);
  }
  return parsed;
}

function parseBooleanFlag(name, value) {
  if (value === '0' || value === 'false') {
    return false;
  }
  if (value === '1' || value === 'true') {
    return true;
  }
  throw new Error(`${name} must be 0 or 1`);
}

function parseAuditTarget(value) {
  if (AUDIT_TARGETS.has(value)) {
    return value;
  }
  throw new Error(`DASHBOARD_PERFORMANCE_AUDIT_TARGET must be one of: ${[...AUDIT_TARGETS].join(', ')}`);
}

function parseArgs(args, env = process.env) {
  const options = {
    target: parseAuditTarget(env.DASHBOARD_PERFORMANCE_AUDIT_TARGET || 'vps-runtime'),
    latencyArtifactDir: env.DASHBOARD_API_LATENCY_ARTIFACT_DIR || '.artifacts/dashboard-api-latency',
    frontendSmokeHistory: env.FRONTEND_SMOKE_HISTORY_JSONL || '.artifacts/frontend-smoke-performance/history.jsonl',
    frontendSmokeReport: env.FRONTEND_SMOKE_REPORT_MD || '.artifacts/frontend-smoke-performance/latest.md',
    systemdUnitDir: env.DASHBOARD_LATENCY_SYSTEMD_UNIT_DIR || '/etc/systemd/system',
    systemdServiceName: env.DASHBOARD_LATENCY_SYSTEMD_SERVICE_NAME || 'aios-dashboard-latency-observation',
    maxAgeHours: parsePositiveNumber(
      'DASHBOARD_PERF_AUDIT_MAX_AGE_HOURS',
      env.DASHBOARD_PERF_AUDIT_MAX_AGE_HOURS || '168',
    ),
    requireCacheHit: parseBooleanFlag(
      'DASHBOARD_PERF_AUDIT_REQUIRE_CACHE_HIT',
      env.DASHBOARD_PERF_AUDIT_REQUIRE_CACHE_HIT || '1',
    ),
    skipFrontendSmoke: false,
    skipSystemd: false,
    json: false,
    help: false,
  };

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    switch (arg) {
      case '--target':
        options.target = parseAuditTarget(readValueArg(args, index, arg));
        index += 1;
        break;
      case '--latency-artifact-dir':
        options.latencyArtifactDir = readValueArg(args, index, arg);
        index += 1;
        break;
      case '--frontend-smoke-history':
        options.frontendSmokeHistory = readValueArg(args, index, arg);
        index += 1;
        break;
      case '--frontend-smoke-report':
        options.frontendSmokeReport = readValueArg(args, index, arg);
        index += 1;
        break;
      case '--systemd-unit-dir':
        options.systemdUnitDir = readValueArg(args, index, arg);
        index += 1;
        break;
      case '--systemd-service-name':
        options.systemdServiceName = readValueArg(args, index, arg);
        index += 1;
        break;
      case '--max-age-hours':
        options.maxAgeHours = parsePositiveNumber(arg, readValueArg(args, index, arg));
        index += 1;
        break;
      case '--require-cache-hit':
        options.requireCacheHit = parseBooleanFlag(arg, readValueArg(args, index, arg));
        index += 1;
        break;
      case '--skip-systemd':
        options.skipSystemd = true;
        break;
      case '--skip-frontend-smoke':
        options.skipFrontendSmoke = true;
        break;
      case '--json':
        options.json = true;
        break;
      case '--help':
      case '-h':
        options.help = true;
        break;
      default:
        throw new Error(`Unknown argument: ${arg}`);
    }
  }

  if (options.target === 'local-artifacts') {
    options.skipSystemd = true;
  }

  return options;
}

function fileStatus(filePath) {
  if (!existsSync(filePath)) {
    return {
      ok: false,
      evidence: filePath,
      finding: 'missing file',
    };
  }
  const stat = statSync(filePath);
  if (!stat.isFile()) {
    return {
      ok: false,
      evidence: filePath,
      finding: 'not a regular file',
    };
  }
  if (stat.size <= 0) {
    return {
      ok: false,
      evidence: filePath,
      finding: 'empty file',
    };
  }
  return {
    ok: true,
    evidence: `${filePath} (${stat.size} bytes)`,
  };
}

function addFileItem(items, id, label, filePath) {
  const status = fileStatus(filePath);
  items.push({
    id,
    label,
    status: status.ok ? 'pass' : 'fail',
    evidence: status.evidence,
    finding: status.finding,
  });
}

function parseJsonLine(line, filePath) {
  try {
    return JSON.parse(line);
  } catch (error) {
    throw new Error(`${filePath}: failed to parse JSONL line: ${error.message}`);
  }
}

function readLastJsonRecord(filePath) {
  if (!existsSync(filePath)) {
    return null;
  }
  const lines = readFileSync(filePath, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
  if (lines.length === 0) {
    return null;
  }
  return parseJsonLine(lines.at(-1), filePath);
}

function hoursSince(timestamp, now = Date.now()) {
  const millis = Date.parse(timestamp);
  if (!Number.isFinite(millis)) {
    return Infinity;
  }
  return (now - millis) / 3_600_000;
}

function addHistoryFreshnessItem(items, id, label, record, maxAgeHours) {
  if (!record) {
    items.push({
      id,
      label,
      status: 'fail',
      evidence: 'N/A',
      finding: 'missing history record',
    });
    return;
  }
  const ageHours = hoursSince(record.timestamp);
  const status = Number.isFinite(ageHours) && ageHours <= maxAgeHours ? 'pass' : 'fail';
  items.push({
    id,
    label,
    status,
    evidence: `${record.timestamp ?? 'missing timestamp'} (ageHours=${Number.isFinite(ageHours) ? ageHours.toFixed(2) : 'invalid'})`,
    finding: status === 'pass' ? undefined : `history record is older than ${maxAgeHours}h or has invalid timestamp`,
  });
}

function addDashboardLatencyRecordItems(items, record, options) {
  if (!record) {
    items.push({
      id: 'dashboard-latency-history-record',
      label: 'Dashboard latency history has a latest record',
      status: 'fail',
      evidence: 'N/A',
      finding: 'missing latest dashboard latency history record',
    });
    return;
  }

  items.push({
    id: 'dashboard-latency-status',
    label: 'Latest dashboard latency observation passed',
    status: record.status === 'pass' ? 'pass' : 'fail',
    evidence: `status=${record.status ?? 'missing'}`,
    finding: record.status === 'pass' ? undefined : 'latest dashboard latency record is not pass',
  });

  for (const endpoint of ENDPOINTS) {
    const summary = record.measuredSummary?.[endpoint];
    const durationP95 = summary?.durationMs?.p95;
    const payloadMax = summary?.payloadBytes?.max;
    const cacheHitP95 = summary?.serverTimingPhases?.cache_hit?.p95;
    const hasDuration = Number.isFinite(durationP95);
    const hasPayload = Number.isFinite(payloadMax);
    const hasCacheHit = Number.isFinite(cacheHitP95);

    items.push({
      id: `dashboard-latency-${endpoint}-duration`,
      label: `${endpoint} latency record has numeric duration p95`,
      status: hasDuration ? 'pass' : 'fail',
      evidence: `durationP95Ms=${hasDuration ? durationP95 : 'N/A'}`,
      finding: hasDuration ? undefined : 'missing numeric duration p95',
    });
    items.push({
      id: `dashboard-latency-${endpoint}-payload`,
      label: `${endpoint} latency record has numeric payload max`,
      status: hasPayload ? 'pass' : 'fail',
      evidence: `payloadMaxBytes=${hasPayload ? payloadMax : 'N/A'}`,
      finding: hasPayload ? undefined : 'missing numeric payload max',
    });
    if (options.requireCacheHit) {
      items.push({
        id: `dashboard-latency-${endpoint}-cache-hit`,
        label: `${endpoint} latency record has numeric cache_hit p95`,
        status: hasCacheHit ? 'pass' : 'fail',
        evidence: `cacheHitP95Ms=${hasCacheHit ? cacheHitP95 : 'N/A'}`,
        finding: hasCacheHit ? undefined : 'missing numeric cache_hit p95',
      });
    }
  }
}

function addFrontendSmokeRecordItems(items, record) {
  if (!record) {
    items.push({
      id: 'frontend-auth-smoke-history-record',
      label: 'Authenticated frontend smoke history has a latest record',
      status: 'fail',
      evidence: 'N/A',
      finding: 'missing latest frontend smoke history record',
    });
    return;
  }

  const authenticated = record.profile?.authenticated === true;
  const performanceBudget = record.profile?.performanceBudget === true;
  const checked = Number.isFinite(record.checked) ? record.checked : 0;
  items.push({
    id: 'frontend-auth-smoke-status',
    label: 'Latest authenticated frontend smoke passed',
    status: record.status === 'pass' ? 'pass' : 'fail',
    evidence: `status=${record.status ?? 'missing'}`,
    finding: record.status === 'pass' ? undefined : 'latest frontend smoke record is not pass',
  });
  items.push({
    id: 'frontend-auth-smoke-profile',
    label: 'Frontend smoke used authenticated performance profile',
    status: authenticated && performanceBudget ? 'pass' : 'fail',
    evidence: `authenticated=${authenticated} performanceBudget=${performanceBudget}`,
    finding: authenticated && performanceBudget ? undefined : 'latest frontend smoke record is not authenticated performance evidence',
  });
  items.push({
    id: 'frontend-auth-smoke-routes',
    label: 'Frontend smoke checked at least one route',
    status: checked > 0 ? 'pass' : 'fail',
    evidence: `checked=${checked}`,
    finding: checked > 0 ? undefined : 'latest frontend smoke record checked no routes',
  });
}

function buildAudit(options) {
  const items = [];
  const latencyFiles = {
    latestMd: path.join(options.latencyArtifactDir, 'latest.md'),
    dailyMd: path.join(options.latencyArtifactDir, 'daily.md'),
    weeklyMd: path.join(options.latencyArtifactDir, 'weekly.md'),
    historyJsonl: path.join(options.latencyArtifactDir, 'history.jsonl'),
  };

  addFileItem(items, 'dashboard-latency-latest-md', 'Dashboard latency latest.md exists', latencyFiles.latestMd);
  addFileItem(items, 'dashboard-latency-daily-md', 'Dashboard latency daily.md exists', latencyFiles.dailyMd);
  addFileItem(items, 'dashboard-latency-weekly-md', 'Dashboard latency weekly.md exists', latencyFiles.weeklyMd);
  addFileItem(items, 'dashboard-latency-history-jsonl', 'Dashboard latency history.jsonl exists', latencyFiles.historyJsonl);

  const latencyRecord = readLastJsonRecord(latencyFiles.historyJsonl);
  addHistoryFreshnessItem(
    items,
    'dashboard-latency-freshness',
    'Dashboard latency evidence is fresh',
    latencyRecord,
    options.maxAgeHours,
  );
  addDashboardLatencyRecordItems(items, latencyRecord, options);

  if (!options.skipFrontendSmoke) {
    addFileItem(items, 'frontend-auth-smoke-history-jsonl', 'Authenticated frontend smoke history exists', options.frontendSmokeHistory);
    addFileItem(items, 'frontend-auth-smoke-report-md', 'Authenticated frontend smoke latest report exists', options.frontendSmokeReport);
    const frontendRecord = readLastJsonRecord(options.frontendSmokeHistory);
    addHistoryFreshnessItem(
      items,
      'frontend-auth-smoke-freshness',
      'Authenticated frontend smoke evidence is fresh',
      frontendRecord,
      options.maxAgeHours,
    );
    addFrontendSmokeRecordItems(items, frontendRecord);
  }

  if (!options.skipSystemd) {
    addFileItem(
      items,
      'dashboard-latency-systemd-service',
      'Dashboard latency systemd service unit is installed',
      path.join(options.systemdUnitDir, `${options.systemdServiceName}.service`),
    );
    addFileItem(
      items,
      'dashboard-latency-systemd-timer',
      'Dashboard latency systemd timer unit is installed',
      path.join(options.systemdUnitDir, `${options.systemdServiceName}.timer`),
    );
  } else {
    items.push({
      id: 'dashboard-latency-systemd-scope',
      label: 'Dashboard latency systemd verification scope is explicit',
      status: 'pass',
      evidence: `target=${options.target}; skipSystemd=${options.skipSystemd}`,
    });
  }

  const failed = items.filter((item) => item.status !== 'pass');
  return {
    status: failed.length === 0 ? 'pass' : 'fail',
    options,
    summary: {
      passed: items.length - failed.length,
      failed: failed.length,
      total: items.length,
    },
    items,
  };
}

function printHuman(audit) {
  console.log(`[dashboard-performance-completion-audit] ${audit.status}`);
  console.log(`[dashboard-performance-completion-audit] passed=${audit.summary.passed} failed=${audit.summary.failed} total=${audit.summary.total}`);
  for (const item of audit.items) {
    const marker = item.status === 'pass' ? 'PASS' : 'FAIL';
    console.log(`[${marker}] ${item.id}: ${item.evidence}`);
    if (item.finding) {
      console.log(`  finding: ${item.finding}`);
    }
  }
}

function main() {
  try {
    const options = parseArgs(process.argv.slice(2));
    if (options.help) {
      printUsage();
      return;
    }
    const audit = buildAudit(options);
    if (options.json) {
      console.log(JSON.stringify(audit, null, 2));
    } else {
      printHuman(audit);
    }
    if (audit.status !== 'pass') {
      process.exitCode = 1;
    }
  } catch (error) {
    console.error(`[dashboard-performance-completion-audit] ${error.message}`);
    process.exitCode = 2;
  }
}

main();
